"""Regenerate tests/data/cases.rs from the rule table of tests/test_lint.py (CASES).

    .venv/bin/python native/klong-lint/gen_cases.py > native/klong-lint/tests/data/cases.rs
"""
import sys
sys.path.insert(0, ".")
from tests.test_lint import CASES


def lit(s):
    out = ['"']
    for c in s:
        if c == '\\': out.append('\\\\')
        elif c == '"': out.append('\\"')
        elif c == '\n': out.append('\\n')
        elif c == '\r': out.append('\\r')
        elif c == '\t': out.append('\\t')
        elif ord(c) < 32 or ord(c) == 127: out.append('\\x%02x' % ord(c))
        else: out.append(c)
    out.append('"')
    return "".join(out)


print("// Generated by gen_cases.py from CASES of tests/test_lint.py: (code, source, [(line, col)] of every finding of that code).")
print("pub static CASES: &[(&str, &str, &[(usize, usize)])] = &[")
for code, text, want in CASES:
    print(f'    ({lit(code)}, {lit(text)}, &[{", ".join(f"({a}, {b})" for a, b in want)}]),')
print("];")
