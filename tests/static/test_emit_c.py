# Helpers a compiler may call for arithmetic the target has no instruction for. They come
# from the compiler's own runtime library (compiler-rt or libgcc), which every bare-metal
# link includes; they are not libc. Soft-float (__aeabi_f*, __aeabi_d*, __*sf3, __*df3 and
# the conversions) appears on cores without an FPU, or for a double kg_float on a core
# with a single-precision FPU; 64-bit integer multiply, divide and shift (__aeabi_l*,
# __*di3) for a 64-bit kg_int on a 32-bit core; __aeabi_idiv and friends on cores without
# a divide instruction. memcpy and memset are defined by klong_rt.h itself.
COMPILER_RT = re.compile(r"__aeabi_[a-z0-9_]+\Z|__(add|sub|mul|div|neg|eq|ne|lt|le|gt|ge|unord|cmp)[sd]f[23]\Z|"
                         r"__(fix|fixuns|float|floatun)[sd][if][sd][if]\Z|__(extendsfdf2|truncdfsf2)\Z|"
                         r"__(u?div|u?mod|mul|ashl|ashr|lshr|u?divmod)[sd]i[34]\Z")

CROSS = (
    ("thumbv6m-none-eabi", []),                                             # Cortex-M0: no FPU, no divide
    ("thumbv7em-none-eabihf", ["-mcpu=cortex-m4", "-mfpu=fpv4-sp-d16"]),    # single-precision FPU
    ("armv7m-none-eabi", []),
    ("armebv7m-none-eabi", []),                                             # big endian
    ("riscv32-unknown-elf", ["-march=rv32imafc", "-mabi=ilp32f"]),
    ("i386-unknown-none-elf", []),
    ("aarch64-none-elf", []),
)


def emit_dir(path_or_text, int_bits=32, float_bits=32, **kw):
    d = tempfile.mkdtemp(prefix="kgemit_")
    if os.path.isfile(path_or_text):
        e = emit_program(path_or_text, d, int_bits=int_bits, float_bits=float_bits, **kw)
    else:
        e = emit_program("t.kg", d, text=path_or_text, int_bits=int_bits, float_bits=float_bits, externs=STUBS, **kw)
    return d, e


def compile_obj(d, prefix, flags, cc=None):
    obj = os.path.join(d, prefix + ".o")
    r = subprocess.run([cc or CC] + list(flags) + ["-c", os.path.join(d, prefix + ".c"), "-o", obj], capture_output=True, text=True)
    return r, obj


def undefined(obj):
    out = subprocess.run(["nm", "-u", obj], capture_output=True, text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if parts:
            names.append(parts[-1])
    return sorted(names)


def strip_us(names):
    """Mach-O prefixes C names with an underscore."""
    import sys
    return sorted(n[1:] if sys.platform == "darwin" and n.startswith("_") else n for n in names)


def function_body(c, name):
    m = re.search(r"^static [^\n]*\b" + re.escape(name) + r"\([^\n]*\) \{\n(.*?)^\}", c, re.S | re.M)
    return m.group(1)


class TestFiles(unittest.TestCase):
    def test_three_files_are_written(self):
        d, e = emit_dir(os.path.join(EMBEDDED, "mavg.kg"))
        self.assertEqual(sorted(os.listdir(d)), ["klong_rt.h", "mavg.c", "mavg.h"])
        with open(os.path.join(d, "klong_rt.h")) as f, open(runtime_header()) as g:
            self.assertEqual(f.read(), g.read())
        self.assertTrue(e.c.startswith("/* mavg.c - generated by KlongPy"))

    def test_the_runtime_header_is_package_data(self):
        self.assertTrue(os.path.isfile(runtime_header()))
        with open(os.path.join(ROOT, "pyproject.toml")) as f:
            self.assertIn('"static/*.h"', f.read())

    def test_the_header_declares_the_instance_init_entries_and_externs(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "pid.kg"))
        h = e.h
        for text in ("struct pid {", "typedef struct pid pid_t;", "typedef struct pid pid_storage_t;", "#define PID_SIZE",
                     "void pid_init(pid_t *p);", "size_t pid_size(void);",
                     "kg_float pid_step(pid_t *p, kg_float x);",
                     "kg_float read_adc(kg_int a0);", "kg_int write_pwm(kg_int a0, kg_float a1);",
                     "Klong name read.adc"):
            self.assertIn(text, h)
        self.assertNotIn("math.h", h + e.c)

    def test_an_array_result_is_an_out_pointer(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "fir.kg"))
        self.assertIn("void fir_run(fir_t *p, const kg_float *x /* [256] */, kg_float *out /* [241] */);", e.h)

    def test_only_stdint_and_stddef_are_included_and_math_only_for_float_power(self):
        with open(runtime_header()) as f:
            rt = f.read()
        self.assertEqual(sorted(set(re.findall(r"#include <([a-z.]+)>", rt))), ["math.h", "stddef.h", "stdint.h"])
        _, e = emit_dir('f::{x^y}\n.entry("f";"float float -> float")')
        self.assertIn("#define KG_NEED_MATH 1", e.h)
        self.assertTrue(e.report["need_math"])
        _, e = emit_dir('f::{x^3}\n.entry("f";"int -> int")')
        self.assertNotIn("KG_NEED_MATH", e.h)
        for text in (e.h, e.c):
            self.assertEqual(re.findall(r"#include <", text), [])

    def test_each_statement_carries_file_and_line(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "mavg.kg"))
        self.assertIn("/* mavg.kg:15: buf::buf:=x,pos */", e.c)
        self.assertNotIn("#line", e.c)
        _, e = emit_dir(os.path.join(EMBEDDED, "mavg.kg"), line_directives=True)
        self.assertIn('#line 15 "mavg.kg"', e.c)

    def test_nothing_names_a_board(self):
        with open(runtime_header()) as f:
            text = f.read().lower()
        for name in PROGRAMS:
            _, e = emit_dir(os.path.join(EMBEDDED, name + ".kg"))
            text += (e.c + e.h).lower()
        for word in ("esp32", "stm32", "cortex", "arduino", "riscv", "xtensa", "nrf5", "rp2040", "avr"):
            self.assertNotIn(word, text)


class TestNames(unittest.TestCase):
    def test_names_follow_the_rule(self):
        _, e = emit_dir('sq::{x*x}\nf::{sq(x)+sq(1.5)}\n.entry("f";"int -> float")')
        self.assertRegex(e.c, r"static kg_int kg_sq__\d\(t_t \*p, kg_int a0_x\)")
        self.assertRegex(e.c, r"static kg_float kg_sq__\d\(t_t \*p, kg_float a0_x\)")
        self.assertIn("kg_float t_f(t_t *p, kg_int x)", e.c)

    def test_prefix_option(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "pid.kg"), prefix="ctl")
        self.assertIn("kg_float ctl_step(ctl_t *p, kg_float x);", e.h)
        for bad in ("kg_x", "kg", "9x", "a-b"):
            with self.assertRaises(ValueError):
                emit_dir(os.path.join(EMBEDDED, "pid.kg"), prefix=bad)

    def test_several_entries_of_one_function(self):
        _, e = emit_dir('f::{+/x}\n.entry("f";"float[4] -> float")\n.entry("f";"int[2,3] -> int[3]")')
        self.assertIn("kg_float t_f__f4(t_t *p, const kg_float *x /* [4] */);", e.h)
        self.assertIn("void t_f__i2x3(t_t *p, const kg_int *x /* [2,3] */, kg_int *out /* [3] */);", e.h)

    def test_an_extern_that_collides_with_a_generated_name_is_an_error(self):
        text = '.extern("t.f";"int -> int")\nf::{t.f(x)}\n.entry("f";"int -> int")'
        with self.assertRaises(KlongStaticError) as cm:
            emit_program("t.kg", None, text=text, prefix="t")
        self.assertIn("[extern]", str(cm.exception))
        emit_program("t.kg", None, text=text, prefix="other")

    def test_c_keywords_as_klong_names_are_harmless(self):
        text = 'int::{[for];for::x+1;for*2}\nf(double;while)::{int(double)+while}\n.entry("f";"int int -> int")'
        d, e = emit_dir(text)
        if CC:
            r, _ = compile_obj(d, "t", WARN)
            self.assertEqual(r.stderr, "")


class TestEquivalenceOfCheckerAndEmitter(unittest.TestCase):
    """No operator the checker accepts is missing from the emitter, and none the emitter has is rejected."""

    def test_the_three_sets_are_one(self):
        allowed = {op.id for op in OPTABLE if op.status == "allowed"}
        self.assertEqual(allowed, set(C_EXPANSION))
        self.assertEqual(allowed, set(HANDLED))

    def test_every_expression_row_has_a_form_for_each_type_it_takes(self):
        for rid, (kind, as_int, as_float) in C_EXPANSION.items():
            self.assertIn(kind, ("expr", "view", "const", "loop", "stmt"), rid)
            if kind == "expr":
                self.assertTrue(as_int or as_float, rid)

    def test_every_example_of_every_allowed_row_and_form_is_emitted(self):
        seen = set()
        for op in OPTABLE:
            for ex in op.examples:
                with self.subTest(row=op.id, body=ex[0]):
                    e = emit_program("t.kg", None, text=f'f::{{{ex[0]}}}\n.entry("f";"{ex[1]}")')
                    self.assertIn("t_f(", e.c)
                    seen.add(op.id)
        for form in FORMS:
            for prog, sig in form.examples:
                with self.subTest(form=form.id):
                    emit_program("t.kg", None, text=f'{prog}\n.entry("f";"{sig}")', externs=STUBS)
        self.assertEqual({op.id for op in OPTABLE if op.status == "allowed"} - seen, {"define"})

    def test_every_accept_fixture_is_emitted(self):
        import glob
        here = os.path.dirname(os.path.abspath(__file__))
        for path in sorted(glob.glob(os.path.join(here, "accept", "*.kg"))):
            with self.subTest(fixture=os.path.basename(path)):
                d, e = emit_dir(path, externs=STUBS)
                if CC:
                    r, _ = compile_obj(d, e.prefix, WARN)
                    self.assertEqual(r.stderr, "")

    def test_rejected_rows_never_reach_the_emitter(self):
        written = {"monad": "{0}x", "dyad": "x{0}y", "adverb1": "{{x}}{0}x", "adverb2": "x{{x}}{0}y"}
        for op in OPTABLE:
            if op.status == "allowed":
                continue
            body = written[op.valence].format(op.glyph)
            with self.subTest(row=op.id):
                with self.assertRaises(KlongStaticError):
                    emit_program("t.kg", None, text=f'f::{{{body}}}\n.entry("f";"int[3] int[3] -> int")')


class TestFusionAndStorage(unittest.TestCase):
    def test_golden_c(self):
        golden(self, "dot.c", emit_dir(DOT)[1].c)
        golden(self, "axpy.c", emit_dir(AXPY)[1].c)
        for name in ("mavg", "pid"):
            golden(self, name + ".c", emit_dir(os.path.join(EMBEDDED, name + ".kg"))[1].c)
        fir = emit_dir(os.path.join(EMBEDDED, "fir.kg"))[1].c
        golden(self, "fir_run.c", fir[fir.index("static void kg_run__1(fir_t *p, const kg_float *a0_x, kg_float *out);"):])

    def test_dot_product_is_one_loop_and_no_temporary_array(self):
        _, e = emit_dir(DOT)
        body = function_body(e.c, "kg_f__1")
        self.assertEqual(body.count("for ("), 1)
        self.assertIn("t1 = (t1 + (a0_x[i2] * a1_y[i2]));", body)
        self.assertEqual(e.report["slot_bytes"], 0)
        self.assertIn("kg_unused", e.h)

    def test_a_tree_of_atomic_operators_is_one_loop_into_the_result(self):
        _, e = emit_dir(AXPY)
        body = function_body(e.c, "kg_f__0")
        self.assertEqual(body.count("for ("), 1)
        self.assertIn("out[i1] = (a0_x[i1] + (a1_y[i1] * a2_z[i1]));", body)
        self.assertEqual(e.report["slot_bytes"], 0)

    def test_fir_needs_no_16_by_241_temporary(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "fir.kg"))
        self.assertEqual(e.report["slot_bytes"], 0)
        self.assertNotIn("3856]; /*", e.h)
        body = function_body(e.c, "kg_run__1")
        self.assertIn("a0_x[kg_c_idx[", body)         # the gather is read through the index table
        self.assertNotIn("kg_ix(", body)              # whose values were checked at compile time

    def test_the_state_update_of_mavg_is_in_place(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "mavg.kg"))
        body = function_body(e.c, "kg_step__1")
        self.assertIn("p->g_buf[kg_ix(t1, 4, 15)] = a0_x;", body)
        self.assertEqual(e.report["slot_bytes"], 0)
        self.assertEqual(e.report["state_bytes"], 20)

    def test_an_assignment_that_reads_its_target_out_of_step_goes_through_a_slot(self):
        _, e = emit_dir('buf::[1.0 2.0 3.0 4.0]\nf::{buf::(1_buf),x;buf::buf*2;+/buf}\n.entry("f";"float -> float")')
        body = function_body(e.c, "kg_f__1")
        self.assertIn("p->f1_t0[", body)                              # the shift reads buf at i+1 while writing i
        self.assertIn("p->g_buf[i", body)
        self.assertRegex(body, r"p->g_buf\[(i\d+)\] = \(p->g_buf\[\1\] \* ")   # the scaling is in place
        self.assertEqual(e.report["slot_bytes"], 16)

    def test_slots_of_statements_that_do_not_overlap_share_storage(self):
        text = ('f::{[a b];a::[;x;x+1;x+2];b::[;x*2;x*3;x*4];(+/a)+(+/b)}\n.entry("f";"float -> float")')
        _, e = emit_dir(text)
        slots = re.findall(r"kg_float (f\d+_t\d+)\[3\]", e.h)
        self.assertEqual(len(slots), 1, e.h)                       # both evaluated lists use one temporary
        self.assertEqual(len(re.findall(r"kg_float f\d+_l\d+_[ab]\[3\]", e.h)), 2)

    def test_integer_arithmetic_is_emitted_unsigned(self):
        _, e = emit_dir('f::{(x+y)*x-y}\n.entry("f";"int int -> int")')
        self.assertIn("kg_imul(kg_iadd(a0_x, a1_y), kg_isub(a0_x, a1_y))", e.c)
        with open(runtime_header()) as f:
            self.assertIn("return (kg_int)((kg_uint)a + (kg_uint)b);", f.read())

    def test_side_effects_are_statements_in_klong_order(self):
        text = ('.extern("rd";"int -> int")\nf::{rd(1)-rd(2)*rd(3)}\n.entry("f";"-> int")')
        _, e = emit_dir(text)
        body = function_body(e.c, "kg_f__0")
        order = re.findall(r"= rd\((\d)\);", body)
        self.assertEqual(order, ["3", "2", "1"])                    # the right operand of a dyad first


class TestSizeReport(unittest.TestCase):
    LINE = re.compile(r"# size int(\d+)/float(\d+): constants=(\d+) instance=(\d+) stack=(\d+) c_lines=(\d+)")

    def recorded(self, name):
        out = {}
        with open(os.path.join(EMBEDDED, name + ".expect")) as f:
            for line in f:
                m = self.LINE.match(line)
                if m:
                    v = [int(x) for x in m.groups()]
                    out[(v[0], v[1])] = dict(const_bytes=v[2], instance_bytes=v[3], stack_bytes=v[4], c_lines=v[5])
        return out

    def test_the_report_is_recorded_and_no_size_grows_by_more_than_ten_percent(self):
        for name in PROGRAMS:
            rec = self.recorded(name)
            for cfg in CONFIGS:
                with self.subTest(program=name, config=cfg):
                    self.assertIn(cfg, rec, f"{name}.expect has no '# size int{cfg[0]}/float{cfg[1]}:' line")
                    _, e = emit_dir(os.path.join(EMBEDDED, name + ".kg"), *cfg)
                    for key, was in rec[cfg].items():
                        self.assertLessEqual(e.report[key], was * 1.10 + 0.5, f"{key} grew: recorded {was}, now {e.report[key]}")

    def test_the_report_names_the_chain_and_prints(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "pid.kg"))
        r = e.report
        self.assertEqual(r["call_chain"], ["pid_step", "kg_step__1", "kg_clamp__0"])
        self.assertEqual(r["call_depth"], 3)
        self.assertGreater(r["stack_bytes"], 0)
        text = e.report_text()
        for word in ("constants", "sizeof(pid_t)", "deepest call chain", "stack estimate"):
            self.assertIn(word, text)

    def test_constants_count_the_tables(self):
        _, e = emit_dir(os.path.join(EMBEDDED, "fir.kg"))
        self.assertEqual(e.report["const_bytes"], 4 * (16 + 16 * 241))
        _, e = emit_dir(os.path.join(EMBEDDED, "fir.kg"), 64, 64)
        self.assertEqual(e.report["const_bytes"], 8 * (16 + 16 * 241))

    @needs_cc
    def test_the_reported_instance_size_is_sizeof(self):
        for name in PROGRAMS:
            for cfg in CONFIGS + ((64, 32), (32, 64)):
                with self.subTest(program=name, config=cfg):
                    with open(os.path.join(EMBEDDED, name + ".kg")) as f:
                        b = Build(f.read(), name=name if name != "pid" else "pidc", int_bits=cfg[0], float_bits=cfg[1],
                                  externs={"read.adc": lambda ch: 0.3, "write.pwm": lambda ch, duty: 0})
                    self.assertEqual(b.size, b.emitted.report["instance_bytes"])


