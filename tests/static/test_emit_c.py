def compilers():
    """The distinct C compilers on the path."""
    seen, out = set(), []
    for name in (os.environ.get("KG_TEST_CC"), "cc", "clang", "gcc"):
        path = shutil.which(name) if name else None
        if not path:
            continue
        version = subprocess.run([path, "--version"], capture_output=True, text=True).stdout.splitlines()[:1]
        key = (os.path.realpath(path), tuple(version))
        if key[1] not in seen:
            seen.add(key[1])
            out.append(path)
    return out


